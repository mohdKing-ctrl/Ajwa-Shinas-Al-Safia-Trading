  /* ---------------------------------------------------------- engine */
  var lang = 'ar';

  function t(key, vars) {
    var s = (D[lang] && D[lang][key] !== undefined) ? D[lang][key] : (D.en[key] !== undefined ? D.en[key] : key);
    if (vars) s = s.replace(/\{(\w+)\}/g, function (m, k) { return vars[k] !== undefined ? vars[k] : m; });
    return s;
  }
  /* pick(en, ar): the text in the current language, falling back to the other one. */
  function pick(en, ar) { return lang === 'ar' ? (ar || en || '') : (en || ar || ''); }

  function apply() {
    var root = document.documentElement;
    root.lang = lang; root.dir = lang === 'ar' ? 'rtl' : 'ltr';
    document.querySelectorAll('[data-i18n]').forEach(function (el) { el.textContent = t(el.getAttribute('data-i18n')); });
    document.querySelectorAll('[data-i18n-ph]').forEach(function (el) { el.placeholder = t(el.getAttribute('data-i18n-ph')); });
    document.querySelectorAll('[data-i18n-title]').forEach(function (el) { el.title = t(el.getAttribute('data-i18n-title')); });
  }
  function setLang(l) { lang = l === 'en' ? 'en' : 'ar'; apply(); }

  window.I18N = { t: t, pick: pick, setLang: setLang, apply: apply, isRTL: function () { return lang === 'ar'; }, get lang() { return lang; }, dict: D };
